    // CREAR INFANTE AQUI ------------------------------------------------------
    public infante crearInfante() {
        int ren = TQuery.getSelectedRow();
        if (ren < 0) {
            JOptionPane.showMessageDialog(this, "Selecciona un renglon de la tabla");
            return null;
        }
        ren = TQuery.convertRowIndexToModel(ren);
        DefaultTableModel modelo = (DefaultTableModel) TQuery.getModel();

        infante kid = new infante();
        kid.curp = String.valueOf(modelo.getValueAt(ren, 0));
        kid.nombre = String.valueOf(modelo.getValueAt(ren, 1));
        kid.sexo = String.valueOf(modelo.getValueAt(ren, 2));
        kid.fecha = String.valueOf(modelo.getValueAt(ren, 3));
        kid.estado = String.valueOf(modelo.getValueAt(ren, 4));
        return kid;
    }
// CREAR EDUCADOR

    public educador crearEducador() {
        DefaultTableModel modelo = (DefaultTableModel) TQuery.getModel();
        int ren = TQuery.getSelectedRow();
        educador edu = new educador();

        if (ren >= 0) {
            edu.curpe = modelo.getValueAt(ren, 0).toString();
            edu.nombree = modelo.getValueAt(ren, 1).toString();
            edu.sexoe = modelo.getValueAt(ren, 2).toString();
            edu.telefonoe = modelo.getValueAt(ren, 3).toString();
            edu.direccione = modelo.getValueAt(ren, 4).toString();
            edu.estadoe = modelo.getValueAt(ren, 5).toString();

        } else {
            JOptionPane.showMessageDialog(this, "Selecciona un renglon de la tabla");
        }
        return null;
    }
//CREAR TUTOR ------------------------------------------------------

    public responsable crearTutor() {
        DefaultTableModel modelo = (DefaultTableModel) TQuery.getModel();
        int ren = TQuery.getSelectedRow();
        responsable tut = new responsable();

        if (ren >= 0) {
            tut.curpr = modelo.getValueAt(ren, 0).toString();
            tut.nombrer = modelo.getValueAt(ren, 1).toString();
            tut.sexor = modelo.getValueAt(ren, 2).toString();
            tut.telefono = modelo.getValueAt(ren, 3).toString();
            tut.parentesco = modelo.getValueAt(ren, 4).toString();
            tut.estador = modelo.getValueAt(ren, 5).toString();

        } else {
            JOptionPane.showMessageDialog(this, "Selecciona un renglon de la tabla");
        }
        return null;
    }
//CREAR BITACORA ------------------------------------------------------

    public bitacora crearBitacora() {
        DefaultTableModel modelo = (DefaultTableModel) TQuery.getModel();
        int ren = TQuery.getSelectedRow();
        bitacora bit = new bitacora();

        if (ren >= 0) {
            bit.falta = modelo.getValueAt(ren, 0).toString();
            bit.tiempo = modelo.getValueAt(ren, 1).toString();
            bit.tipo = modelo.getValueAt(ren, 2).toString();
            bit.observaciones = modelo.getValueAt(ren, 3).toString();
            bit.infantes_curp = modelo.getValueAt(ren, 4).toString();
            bit.responsables_curpr = modelo.getValueAt(ren, 5).toString();
            bit.educadores_curpe = modelo.getValueAt(ren, 6).toString();

        } else {
            JOptionPane.showMessageDialog(this, "Selecciona un renglon de la tabla");
        }
        return null;
    }

